// Nome leggibile: minuscole con l'iniziale maiuscola, accenti veri al posto dell'apostrofo.
export function nomePiatto(s){
  if(!s) return "";
  const t = s.replace(/^§/, "").replace(/^\*/, "").toLowerCase()
    .replace(/u'/g, "ù").replace(/e'/g, "è").replace(/\bnr\./g, "n.");
  return t.charAt(0).toUpperCase() + t.slice(1);
}
export const conMaiale = s => /^§/.test(s || "");
